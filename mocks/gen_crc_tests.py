#!/usr/bin/env python3
"""Generate CRC-16/MODBUS test vectors as a C header.

Requires: pip install crccheck

Usage: python3 gen_crc_tests.py [num_random_blocks] [seed] > crc16_vectors.h

CRC-16/MODBUS: poly 0x8005 (reflected: 0xA001), init 0xFFFF,
input/output reflected, no final XOR. Check value for "123456789" is 0x4B37.
The expected values come from the third-party `crccheck` library, so no CRC
code written for this project is involved in producing the reference.
"""
import random
import sys

from crccheck.crc import CrcModbus

num_random = int(sys.argv[1]) if len(sys.argv) > 1 else 20
seed = int(sys.argv[2]) if len(sys.argv) > 2 else 12345
rng = random.Random(seed)  # fixed seed -> reproducible vectors


def crc16(data: bytes) -> int:
    return CrcModbus.calc(data)


# Sanity check of the library against the published check value
assert crc16(b"123456789") == 0x4B37, "reference implementation mismatch"

blocks = [
    ("check value '123456789'", b"123456789"),
    ("empty block", b""),
    ("single 0x00", b"\x00"),
    ("single 0xFF", b"\xff"),
    ("leading zeros", b"\x00\x00\x41"),
    ("16 x 0x00", bytes(16)),
    ("16 x 0xFF", b"\xff" * 16),
    ("ascending 0..255", bytes(range(256))),
]
for _ in range(num_random):
    n = rng.randint(1, 64)
    blocks.append((f"random, {n} bytes", bytes(rng.randrange(256) for _ in range(n))))
# one longer block
blocks.append(("random, 1000 bytes", bytes(rng.randrange(256) for _ in range(1000))))

out = []
out.append("/* Auto-generated by gen_crc_tests.py - do not edit by hand. */")
out.append("#ifndef CRC16_VECTORS_H")
out.append("#define CRC16_VECTORS_H")
out.append("#include <stdint.h>")
out.append("#include <stddef.h>")
out.append("")
out.append("typedef struct {")
out.append("    const char    *name;")
out.append("    const uint8_t *data;")
out.append("    size_t         len;")
out.append("    uint16_t       expected;")
out.append("} crc16_vector_t;")
out.append("")

for i, (_, data) in enumerate(blocks):
    if data:
        body = ", ".join(f"0x{b:02X}" for b in data)
        out.append(f"static const uint8_t block_{i}[] = {{ {body} }};")
    else:
        # C forbids zero-length arrays; use a 1-byte dummy, len is 0 in the table
        out.append(f"static const uint8_t block_{i}[] = {{ 0x00 }};")

out.append("")
out.append("static const crc16_vector_t crc16_vectors[] = {")
for i, (name, data) in enumerate(blocks):
    out.append(f'    {{ "{name}", block_{i}, {len(data)}, 0x{crc16(data):04X} }},')
out.append("};")
out.append("")
out.append("#define CRC16_NUM_VECTORS (sizeof(crc16_vectors) / sizeof(crc16_vectors[0]))")
out.append("")
out.append("#endif /* CRC16_VECTORS_H */")

print("\n".join(out))
